// 1. INTEGER LITERALS
let decimal = 42;

console.log("Decimal:", decimal);   //42

let binary = 0b1010;
console.log("Binary 0b1010:", binary);   //10 in decimal

let octal = 0o52;
console.log("Octal 0o52:", octal);   //42 in decimal

let hex = 0x2A;
console.log("Hexadecimal 0x2A:", hex);   //42 in decimal


// 2. Floating Number
 let float1 = 3.14;
 let float2 = -0.5;
 let float3 = .5;
 let float4 = 5.;

 console.log(float1);
 console.log(float2);
 console.log(float3);
 console.log(float4);

 console.log([1,,3].length);    //3
